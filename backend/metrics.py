import time
from flask import request, Response
from prometheus_client import (
    Counter,
    Histogram,
    Gauge,
    generate_latest,
    CONTENT_TYPE_LATEST
)

# Prometheus Metric Definitions
HTTP_REQUESTS_TOTAL = Counter(
    'http_requests_total',
    'Total count of HTTP requests handled by the canteen backend',
    ['method', 'endpoint', 'status']
)

HTTP_REQUEST_DURATION_SECONDS = Histogram(
    'http_request_duration_seconds',
    'Histogram of HTTP request latency in seconds',
    ['method', 'endpoint'],
    buckets=[0.01, 0.05, 0.1, 0.25, 0.5, 1.0, 2.5, 5.0]
)

CANTEEN_CROWD_LEVEL = Gauge(
    'canteen_crowd_level',
    'Current canteen crowd score (1=Low, 2=Moderate, 3=High, 4=Peak)'
)

CANTEEN_ACTIVE_ORDERS = Gauge(
    'canteen_active_orders',
    'Number of active pre-orders currently in queue or preparation'
)

CANTEEN_ESTIMATED_WAIT_MINUTES = Gauge(
    'canteen_estimated_wait_minutes',
    'Estimated waiting time in minutes for new canteen orders'
)

CANTEEN_ORDER_REVENUE_TOTAL = Counter(
    'canteen_order_revenue_total',
    'Total revenue generated by pre-orders in INR'
)

CANTEEN_ITEMS_ORDERED_TOTAL = Counter(
    'canteen_items_ordered_total',
    'Total count of food items ordered',
    ['item_name', 'category']
)


def record_request_metrics(app):
    """
    Middleware to automatically record Prometheus metrics for all incoming requests.
    """
    @app.before_request
    def before_request():
        request._start_time = time.time()

    @app.after_request
    def after_request(response):
        if hasattr(request, '_start_time') and not request.path.startswith('/metrics'):
            latency = time.time() - request._start_time
            endpoint = request.endpoint or request.path
            status_code = str(response.status_code)

            HTTP_REQUEST_DURATION_SECONDS.labels(
                method=request.method,
                endpoint=endpoint
            ).observe(latency)

            HTTP_REQUESTS_TOTAL.labels(
                method=request.method,
                endpoint=endpoint,
                status=status_code
            ).inc()

        return response


def get_metrics_response():
    """
    Handler for /metrics endpoint consumed by Prometheus.
    """
    return Response(generate_latest(), mimetype=CONTENT_TYPE_LATEST)
